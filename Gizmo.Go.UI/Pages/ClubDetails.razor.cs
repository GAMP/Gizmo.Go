using Gizmo.Go.UI.View.Services.Pages;
using Gizmo.Go.UI.View.States.Pages;
using Gizmo.UI.Services;
using Microsoft.AspNetCore.Components;

namespace Gizmo.Go.UI.Pages
{
    public partial class ClubDetails : ComponentBase, IDisposable
    {
        private int _loadedId = -1;

        [Inject]
        private ClubViewState ClubViewState { get; set; } = null!;

        [Inject]
        private ClubViewService ClubViewService { get; set; } = null!;

        [Inject]
        private ILocalizationService LocalizationService { get; set; } = null!;

        [Inject]
        private NavigationManager NavigationManager { get; set; } = null!;

        [Parameter]
        public int Id { get; set; }

        private string PageTitleText =>
            ClubViewState.Details.Value?.Branch.Name ?? LocalizationService.GetString(nameof(Autogenerated.Resources.GO_CLUB_PAGE_TITLE));

        protected override void OnInitialized()
        {
            this.SubscribeChange(ClubViewState);
            base.OnInitialized();
        }

        // the view service has no route (a route with a parameter never matches its navigation events), the page starts the load
        protected override async Task OnParametersSetAsync()
        {
            if (_loadedId == Id)
                return;

            _loadedId = Id;
            await ReloadAsync();
            await base.OnParametersSetAsync();
        }

        public void Dispose()
        {
            this.UnsubscribeChange(ClubViewState);
            ClubViewService.CancelLoad();
        }

        private Task ReloadAsync() => ClubViewService.LoadAsync(Id);

        private Task BackAsync() => ClubViewService.BackAsync(NavigationManager.HistoryEntryState);
    }
}
