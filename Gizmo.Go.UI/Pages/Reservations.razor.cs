using System.Globalization;
using Gizmo.Go.Core.Models.Reservation;
using Gizmo.Go.UI.View.Services.Pages;
using Gizmo.Go.UI.View.States.Pages;
using Gizmo.UI.Services;
using Microsoft.AspNetCore.Components;

namespace Gizmo.Go.UI.Pages
{
    public partial class Reservations : ComponentBase, IDisposable
    {
        [Inject]
        private ReservationsViewState ReservationsViewState { get; set; } = null!;

        [Inject]
        private ReservationsViewService ReservationsViewService { get; set; } = null!;

        [Inject]
        private ILocalizationService LocalizationService { get; set; } = null!;

        [Inject]
        private NavigationManager NavigationManager { get; set; } = null!;

        /// <summary>
        /// Gets or sets the id of the only reservation to show; without it (or with an invalid one) the full list is shown.
        /// The query values are strings parsed in <see cref="OnParametersSet"/>: an invalid value shows the full list instead
        /// of failing the page.
        /// </summary>
        [SupplyParameterFromQuery(Name = "id")]
        public string? ReservationId { get; set; }

        /// <summary>
        /// Gets or sets whether the reservation is opened from the Home nearest reservation block (<c>true</c>).
        /// </summary>
        [SupplyParameterFromQuery(Name = "nearest")]
        public string? Nearest { get; set; }

        private string Title => ReservationsViewState.SingleId is not { } id
            ? LocalizationService.GetString(nameof(Autogenerated.Resources.GO_RESERVATIONS_PAGE_TITLE))
            : ReservationsViewState.IsNearest
                ? LocalizationService.GetString(nameof(Autogenerated.Resources.GO_RESERVATIONS_NEAREST_TITLE))
                : LocalizationService.GetString(nameof(Autogenerated.Resources.GO_RESERVATIONS_NUMBER_TITLE), id);

        private string CurrentTitle => ReservationsViewState.Current.Value is { } current
            ? $"{LocalizationService.GetString(nameof(Autogenerated.Resources.GO_RESERVATIONS_CURRENT_TITLE))} · {current.Count}"
            : LocalizationService.GetString(nameof(Autogenerated.Resources.GO_RESERVATIONS_CURRENT_TITLE));

        // the single reservation: current wins while both lists are being reloaded; a canceled one is in the completed list.
        // While a reload after a cancel runs it may be in neither list for a moment (IsReloading keeps the skeleton then)
        private (Reservation? Reservation, bool IsCompleted) FindSingleReservation()
        {
            if (ReservationsViewState.SingleId is not { } id)
                return (null, false);

            if (ReservationsViewState.Current.Value?.FirstOrDefault(reservation => reservation.Id == id) is { } current)
                return (current, false);

            return (ReservationsViewState.Completed.Value?.FirstOrDefault(reservation => reservation.Id == id), true);
        }

        protected override void OnInitialized()
        {
            this.SubscribeChange(ReservationsViewState);
            base.OnInitialized();
        }

        protected override async Task OnInitializedAsync()
        {
            await ReservationsViewService.EnsureLoadedAsync();
            await base.OnInitializedAsync();
        }

        protected override void OnParametersSet()
        {
            int? id = int.TryParse(ReservationId, NumberStyles.None, CultureInfo.InvariantCulture, out var parsedId) ? parsedId : null;
            var isNearest = bool.TryParse(Nearest, out var parsedNearest) && parsedNearest;

            ReservationsViewService.SetView(id, isNearest && id is not null);
            base.OnParametersSet();
        }

        public void Dispose()
        {
            this.UnsubscribeChange(ReservationsViewState);
        }

        private void OnToggleDetails(int id) => ReservationsViewService.ToggleDetails(id);

        private void OnCancel(int id) => ReservationsViewService.RequestCancel(id);

        private void OnKeep() => ReservationsViewService.KeepReservation();

        private Task BackAsync() => ReservationsViewService.BackAsync(NavigationManager.HistoryEntryState);
    }
}
