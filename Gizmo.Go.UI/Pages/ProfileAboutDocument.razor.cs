using Gizmo.Go.UI.View.Services.Pages;
using Gizmo.Go.UI.View.States.Pages;
using Gizmo.UI.Services;
using Microsoft.AspNetCore.Components;

namespace Gizmo.Go.UI.Pages
{
    public partial class ProfileAboutDocument : ComponentBase, IDisposable
    {
        private int _loadedId = -1;

        [Inject]
        private ProfileAboutDocumentViewState ProfileAboutDocumentViewState { get; set; } = null!;

        [Inject]
        private ProfileAboutDocumentViewService ProfileAboutDocumentViewService { get; set; } = null!;

        [Inject]
        private ILocalizationService LocalizationService { get; set; } = null!;

        [Inject]
        private NavigationManager NavigationManager { get; set; } = null!;

        [Parameter]
        public int Id { get; set; }

        // the document title, the generic name for an unknown id
        private string Title => string.IsNullOrEmpty(ProfileAboutDocumentViewState.Title)
            ? LocalizationService.GetString(nameof(Autogenerated.Resources.GO_PROFILE_DOCUMENT_DEFAULT_NAME))
            : ProfileAboutDocumentViewState.Title;

        protected override void OnInitialized()
        {
            this.SubscribeChange(ProfileAboutDocumentViewState);
            base.OnInitialized();
        }

        // the view service has no route (a route with a parameter never matches its navigation events), the page passes the id
        protected override void OnParametersSet()
        {
            if (_loadedId == Id)
                return;

            _loadedId = Id;
            ProfileAboutDocumentViewService.Load(Id);
            base.OnParametersSet();
        }

        public void Dispose()
        {
            this.UnsubscribeChange(ProfileAboutDocumentViewState);
        }

        private Task BackAsync() => ProfileAboutDocumentViewService.BackAsync(NavigationManager.HistoryEntryState);
    }
}
