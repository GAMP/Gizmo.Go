using Gizmo.Go.Core.Models.Agreements;
using Gizmo.Go.UI.Components.Profile;
using Gizmo.Go.UI.View.Services.Pages;
using Gizmo.Go.UI.View.States.Pages;
using Gizmo.UI.Services;
using Microsoft.AspNetCore.Components;

namespace Gizmo.Go.UI.Pages
{
    public partial class ProfilePolicies : ComponentBase, IDisposable
    {
        [Inject]
        private ProfilePoliciesViewState ProfilePoliciesViewState { get; set; } = null!;

        [Inject]
        private ProfilePoliciesViewService ProfilePoliciesViewService { get; set; } = null!;

        [Inject]
        private ILocalizationService LocalizationService { get; set; } = null!;

        [Inject]
        private NavigationManager NavigationManager { get; set; } = null!;

        protected override void OnInitialized()
        {
            this.SubscribeChange(ProfilePoliciesViewState);
            base.OnInitialized();
        }

        protected override async Task OnInitializedAsync()
        {
            await ProfilePoliciesViewService.EnsureLoadedAsync();
            await base.OnInitializedAsync();
        }

        public void Dispose()
        {
            this.UnsubscribeChange(ProfilePoliciesViewState);
        }

        private IReadOnlyList<DocumentList.DocumentListItem> GetItems(IReadOnlyList<UserAgreement> agreements) =>
            agreements
                .Select(x => new DocumentList.DocumentListItem(
                    x.Id,
                    string.IsNullOrWhiteSpace(x.Name) ? LocalizationService.GetString(nameof(Autogenerated.Resources.GO_PROFILE_DOCUMENT_DEFAULT_NAME)) : x.Name))
                .ToList();

        private void OpenPolicy(int id) => ProfilePoliciesViewService.OpenPolicy(id);

        private Task BackAsync() => ProfilePoliciesViewService.BackAsync(NavigationManager.HistoryEntryState);
    }
}
