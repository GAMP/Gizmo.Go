using Gizmo.Go.UI.View.Services.Pages;
using Gizmo.Go.UI.View.States.Pages;
using Gizmo.UI.Services;
using Microsoft.AspNetCore.Components;

namespace Gizmo.Go.UI.Pages
{
    public partial class ProfilePolicy : ComponentBase, IDisposable
    {
        private int _loadedId = -1;

        [Inject]
        private ProfilePolicyViewState ProfilePolicyViewState { get; set; } = null!;

        [Inject]
        private ProfilePolicyViewService ProfilePolicyViewService { get; set; } = null!;

        [Inject]
        private ILocalizationService LocalizationService { get; set; } = null!;

        [Inject]
        private NavigationManager NavigationManager { get; set; } = null!;

        [Parameter]
        public int Id { get; set; }

        // the document name once loaded, otherwise the generic name
        private string Title => ProfilePolicyViewState.Agreement.Value is { } agreement && !string.IsNullOrWhiteSpace(agreement.Name)
            ? agreement.Name
            : LocalizationService.GetString(nameof(Autogenerated.Resources.GO_PROFILE_DOCUMENT_DEFAULT_NAME));

        protected override void OnInitialized()
        {
            this.SubscribeChange(ProfilePolicyViewState);
            base.OnInitialized();
        }

        // the view service has no route (a route with a parameter never matches its navigation events), the page starts the load
        protected override async Task OnParametersSetAsync()
        {
            if (_loadedId == Id)
                return;

            _loadedId = Id;
            await ReloadAsync();
            await base.OnParametersSetAsync();
        }

        public void Dispose()
        {
            this.UnsubscribeChange(ProfilePolicyViewState);
            ProfilePolicyViewService.CancelLoad();
        }

        private Task ReloadAsync() => ProfilePolicyViewService.LoadAsync(Id);

        private Task BackAsync() => ProfilePolicyViewService.BackAsync(NavigationManager.HistoryEntryState);
    }
}
