using Gizmo.UI.Services;
using Microsoft.AspNetCore.Components;
using Microsoft.AspNetCore.Components.Routing;

namespace Gizmo.Go.UI.Layout
{
    public partial class MainLayout : IDisposable
    {
        [Inject]
        private NavigationManager Navigation { get; set; } = null!;
        [Inject] private ILocalizationService LocalizationService { get; set; } = null!;

        private string _pageTitle = string.Empty;

        protected override void OnInitialized()
        {
            Navigation.LocationChanged += OnLocationChanged;
            UpdatePageTitle(Navigation.Uri);
        }

        private void OnLocationChanged(object? sender, LocationChangedEventArgs e)
        {
            UpdatePageTitle(e.Location);
            StateHasChanged();
        }

        private void UpdatePageTitle(string uri)
        {
            var path = new Uri(uri).AbsolutePath.TrimStart('/').ToLowerInvariant();
            _pageTitle = LocalizationService.GetString(path switch
            {
                "branches" => nameof(Autogenerated.Resources.GO_NAV_BRANCHES),
                "favorites" => nameof(Autogenerated.Resources.GO_NAV_FAVORITES),
                "account" => nameof(Autogenerated.Resources.GO_NAV_ACCOUNT),
                "login" => nameof(Autogenerated.Resources.GO_NAV_LOGIN),
                _ => nameof(Autogenerated.Resources.GO_APP_NAME)
            });
        }

        public void Dispose()
        {
            Navigation.LocationChanged -= OnLocationChanged;
        }
    }
}
