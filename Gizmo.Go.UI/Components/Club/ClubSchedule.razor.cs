using System.Globalization;
using Gizmo.Go.Core.Models.Branch;
using Gizmo.Go.UI.Helpers;
using Gizmo.UI.Services;
using Microsoft.AspNetCore.Components;

namespace Gizmo.Go.UI.Components.Club
{
    /// <summary>
    /// Working hours of a club: today and the week. The server has one schedule for all business days, so every business
    /// day shows the same hours and the other days are closed. The club must have business hours.
    /// </summary>
    public partial class ClubSchedule : ComponentBase
    {
        private static readonly DayOfWeek[] WeekDays =
        [
            DayOfWeek.Monday, DayOfWeek.Tuesday, DayOfWeek.Wednesday, DayOfWeek.Thursday,
            DayOfWeek.Friday, DayOfWeek.Saturday, DayOfWeek.Sunday,
        ];

        [Inject]
        private ILocalizationService LocalizationService { get; set; } = null!;

        [Parameter, EditorRequired]
        public Branch Club { get; set; } = null!;

        [Parameter]
        public bool IsExpanded { get; set; }

        [Parameter]
        public EventCallback OnToggle { get; set; }

        private DayOfWeek Today => BranchScheduleHelper.GetBusinessDay(Club, DateTime.UtcNow);

        private bool? IsOpen => BranchScheduleHelper.IsOpen(Club, DateTime.UtcNow);

        private string TodayText =>
            BranchScheduleHelper.IsBusinessWeekDay(Club, Today) ? HoursText : ClosedText;

        private string ClosedText => LocalizationService.GetString(nameof(Autogenerated.Resources.GO_CLUB_CLOSED));

        private string HoursText =>
            BranchScheduleHelper.IsAroundTheClock(Club)
                ? LocalizationService.GetString(nameof(Autogenerated.Resources.GO_HOME_CLUB_AROUND_THE_CLOCK))
                : BranchScheduleHelper.FormatHours(Club, " – ") ?? string.Empty;

        private string DayHours(DayOfWeek day) => BranchScheduleHelper.IsBusinessWeekDay(Club, day) ? HoursText : ClosedText;

        private static string DayName(DayOfWeek day) =>
            Capitalize(CultureInfo.CurrentCulture.DateTimeFormat.GetDayName(day));

        private static string ShortDayName(DayOfWeek day) =>
            Capitalize(CultureInfo.CurrentCulture.DateTimeFormat.GetAbbreviatedDayName(day));

        private static string Capitalize(string name) =>
            name.Length == 0 ? name : char.ToUpper(name[0], CultureInfo.CurrentCulture) + name[1..];
    }
}
