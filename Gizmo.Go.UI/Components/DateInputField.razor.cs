using System.Globalization;
using System.Text;
using Gizmo.UI.Services;
using Microsoft.AspNetCore.Components;

namespace Gizmo.Go.UI.Components
{
    /// <summary>
    /// Digits-only date field with a culture mask (e.g. "__.__.____"), as the client MaskedDateInput,
    /// but driven by the input event so it works with mobile numeric keyboards.
    /// </summary>
    public partial class DateInputField : ComponentBase
    {
        private const int MinYear = 1900;

        [Inject] private ILocalizationService LocalizationService { get; set; } = null!;

        [Parameter] public DateTime? Value { get; set; }
        [Parameter] public EventCallback<DateTime?> ValueChanged { get; set; }

        /// <summary>
        /// Validation message of the bound property (e.g. required), shown when the field has no own message.
        /// </summary>
        [Parameter] public string? ErrorMessage { get; set; }
        [Parameter] public bool Disabled { get; set; }
        [Parameter] public string Id { get; set; } = "date";

        private readonly string _format;
        private readonly int _digitCount;

        private string _text = string.Empty;
        private DateTime? _lastValue;
        private bool _isFocused;
        private string? _localError;
        private string _patternHint = string.Empty;

        public DateInputField()
        {
            _format = BuildFormat(CultureInfo.CurrentCulture);
            _digitCount = _format.Count(IsFormatLetter);
        }

        private string Mask => new(_format.Select(c => IsFormatLetter(c) ? '_' : c).ToArray());

        private string MaskLeft => _text.Length < Mask.Length ? Mask[_text.Length..] : string.Empty;

        private int DigitsEntered => _text.Count(char.IsDigit);

        private bool IsComplete => DigitsEntered == _digitCount;

        private bool ShowMask => _isFocused || (_text.Length > 0 && !IsComplete);

        private bool ShowHint => _isFocused && !IsComplete && _localError is null;

        private string? DisplayedError =>
            _localError ?? (!_isFocused && !string.IsNullOrEmpty(ErrorMessage) ? ErrorMessage : null);

        protected override void OnInitialized()
        {
            var day = LocalizationService.GetString(nameof(Autogenerated.Resources.GO_DATE_INPUT_DAY_LETTER));
            var month = LocalizationService.GetString(nameof(Autogenerated.Resources.GO_DATE_INPUT_MONTH_LETTER));
            var year = LocalizationService.GetString(nameof(Autogenerated.Resources.GO_DATE_INPUT_YEAR_LETTER));

            _patternHint = new string(_format.SelectMany(c => c switch
            {
                'd' => day,
                'M' => month,
                'y' => year,
                _ => c.ToString(),
            }).ToArray());
        }

        protected override void OnParametersSet()
        {
            // external value change (initial value, reset): show it; own emits keep the typed text
            if (Value != _lastValue)
            {
                _lastValue = Value;
                _text = Value?.ToString(_format, CultureInfo.InvariantCulture) ?? string.Empty;
                _localError = null;
            }
        }

        private void OnFocus() => _isFocused = true;

        private void OnBlur()
        {
            _isFocused = false;

            if (_text.Length > 0 && !IsComplete)
                _localError = LocalizationService.GetString(nameof(Autogenerated.Resources.GO_DATE_INPUT_INCOMPLETE));
        }

        private async Task OnInputAsync(ChangeEventArgs e)
        {
            var digits = new string((e.Value?.ToString() ?? string.Empty).Where(char.IsDigit).Take(_digitCount).ToArray());

            _text = Format(digits);
            _localError = null;

            DateTime? date = null;

            if (digits.Length == _digitCount)
            {
                _localError = Validate(out date);
            }

            await EmitAsync(date);
        }

        private async Task EmitAsync(DateTime? date)
        {
            if (date == _lastValue)
                return;

            _lastValue = date;
            await ValueChanged.InvokeAsync(date);
        }

        // "120" -> "12.0": a separator is added only when the next group already has a digit
        private string Format(string digits)
        {
            var sb = new StringBuilder();
            var index = 0;

            foreach (var c in _format)
            {
                if (index >= digits.Length)
                    break;

                if (IsFormatLetter(c))
                    sb.Append(digits[index++]);
                else
                    sb.Append(c);
            }

            return sb.ToString();
        }

        private string? Validate(out DateTime? date)
        {
            date = null;

            var yearText = new string(_format.Zip(_text).Where(p => p.First == 'y').Select(p => p.Second).ToArray());
            var year = int.TryParse(yearText, out var y) ? y : 0;

            if (year < MinYear || year > DateTime.Today.Year)
                return LocalizationService.GetString(nameof(Autogenerated.Resources.GO_DATE_INPUT_CHECK_YEAR));

            if (!DateTime.TryParseExact(_text, _format, CultureInfo.InvariantCulture, DateTimeStyles.None, out var parsed))
                return LocalizationService.GetString(nameof(Autogenerated.Resources.GO_DATE_INPUT_CHECK_DAY_MONTH));

            if (parsed > DateTime.Today)
                return LocalizationService.GetString(nameof(Autogenerated.Resources.GO_DATE_INPUT_CHECK_DAY_MONTH));

            date = parsed;
            return null;
        }

        private static bool IsFormatLetter(char c) => c is 'd' or 'M' or 'y';

        // culture short date pattern normalized to two-digit day / month and four-digit year (client MaskedDateInput)
        private static string BuildFormat(CultureInfo culture)
        {
            var separator = culture.DateTimeFormat.DateSeparator;
            var order = new List<char>();

            foreach (var c in culture.DateTimeFormat.ShortDatePattern)
            {
                if (IsFormatLetter(c) && !order.Contains(c))
                    order.Add(c);
            }

            if (order.Count != 3 || string.IsNullOrEmpty(separator) || separator.Length != 1 || char.IsLetterOrDigit(separator[0]))
                return "dd.MM.yyyy";

            return string.Join(separator, order.Select(c => c switch
            {
                'd' => "dd",
                'M' => "MM",
                _ => "yyyy",
            }));
        }
    }
}
