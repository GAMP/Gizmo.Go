using System.Globalization;
using Gizmo.Go.Core.Models.Reservation;
using Gizmo.Go.UI.Helpers;
using Gizmo.UI.Services;
using Microsoft.AspNetCore.Components;

namespace Gizmo.Go.UI.Components.Reservations
{
    /// <summary>
    /// A reservation of the "My reservations" list: status, payment, date, time, session, cost, PIN, hosts and the cancel area.
    /// </summary>
    public partial class ReservationCard : ComponentBase
    {
        [Inject]
        private ILocalizationService LocalizationService { get; set; } = null!;

        [Parameter, EditorRequired]
        public Reservation Reservation { get; set; } = null!;

        /// <summary>
        /// Gets or sets whether the list of the hosts is expanded.
        /// </summary>
        [Parameter]
        public bool IsExpanded { get; set; }

        /// <summary>
        /// Gets or sets whether the card waits for the cancel confirmation.
        /// </summary>
        [Parameter]
        public bool IsConfirmingCancel { get; set; }

        /// <summary>
        /// Gets or sets whether the cancellation is running.
        /// </summary>
        [Parameter]
        public bool IsCanceling { get; set; }

        /// <summary>
        /// Gets or sets whether the card is in the completed list (no payment block, PIN and cancel).
        /// </summary>
        [Parameter]
        public bool IsCompleted { get; set; }

        [Parameter]
        public EventCallback<int> OnToggleDetails { get; set; }

        [Parameter]
        public EventCallback<int> OnCancel { get; set; }

        [Parameter]
        public EventCallback OnConfirmCancel { get; set; }

        [Parameter]
        public EventCallback OnKeep { get; set; }

        private string StatusModifier => Reservation.Status switch
        {
            GoReservationStatus.Waiting => "upcoming",
            GoReservationStatus.Active => "active",
            GoReservationStatus.Canceled => "canceled",
            GoReservationStatus.Expired => "expired",
            _ => "completed"
        };

        private string StatusText => Localize(ReservationDisplayHelper.GetStatusKey(Reservation));

        private string DateText => ReservationDisplayHelper.GetDateText(Reservation, LocalizationService);

        private string TimeText => ReservationDisplayHelper.GetTimeText(Reservation);

        private string DurationText => ReservationDisplayHelper.GetDurationText(Reservation, LocalizationService);

        private string CostText => ReservationDisplayHelper.GetCostText(Reservation);

        private bool IsCostStruck => Reservation.Status == GoReservationStatus.Canceled && Reservation.Total != 0;

        private bool ShowClubTimeHint => ReservationDisplayHelper.IsClubTimeHintNeeded(Reservation);

        private bool ShowPayment => !IsCompleted && Reservation.PaymentStatus != GoReservationPaymentStatus.NotRequired;

        // a not finalized reservation can reach the completed list after its end, it gets no PIN and no cancel there
        private bool ShowPin => !IsCompleted && ReservationDisplayHelper.ShowPin(Reservation);

        private bool CanCancel => !IsCompleted && ReservationDisplayHelper.CanCancel(Reservation);

        private ReservationRefundState RefundState => ReservationDisplayHelper.GetRefundState(Reservation);

        private string PaymentModifier => Reservation.PaymentStatus switch
        {
            GoReservationPaymentStatus.PartiallySatisfied => "partial",
            GoReservationPaymentStatus.NotSatisfied => "unpaid",
            _ => "paid"
        };

        private string PaymentTitle => Localize(Reservation.PaymentStatus switch
        {
            GoReservationPaymentStatus.PartiallySatisfied => nameof(Autogenerated.Resources.GO_RESERVATIONS_PAYMENT_PARTIAL),
            GoReservationPaymentStatus.NotSatisfied => nameof(Autogenerated.Resources.GO_RESERVATIONS_PAYMENT_NOT_PAID),
            _ => nameof(Autogenerated.Resources.GO_RESERVATIONS_PAYMENT_PAID)
        });

        private string PaymentNote => Localize(Reservation.PaymentStatus switch
        {
            GoReservationPaymentStatus.PartiallySatisfied => nameof(Autogenerated.Resources.GO_RESERVATIONS_PAYMENT_PARTIAL_NOTE),
            GoReservationPaymentStatus.NotSatisfied => nameof(Autogenerated.Resources.GO_RESERVATIONS_PAYMENT_NOT_PAID_NOTE),
            _ => nameof(Autogenerated.Resources.GO_RESERVATIONS_PAYMENT_PAID_NOTE)
        });

        // a partially paid reservation shows the paid part, the others show the total
        private string PaymentAmountText => ReservationDisplayHelper.FormatAmount(
            Reservation.PaymentStatus == GoReservationPaymentStatus.PartiallySatisfied ? ReservationDisplayHelper.GetPaidAmount(Reservation) : Reservation.Total);

        private string PaidText => LocalizationService.GetString(nameof(Autogenerated.Resources.GO_RESERVATIONS_PAYMENT_PAID_AMOUNT),
            ReservationDisplayHelper.FormatAmount(ReservationDisplayHelper.GetPaidAmount(Reservation)));

        private string LeftText => LocalizationService.GetString(nameof(Autogenerated.Resources.GO_RESERVATIONS_PAYMENT_LEFT_AMOUNT),
            ReservationDisplayHelper.FormatAmount(Reservation.Outstanding));

        // paying a reservation is not implemented yet, the button has no handler
        private bool ShowPay => ShowPayment && Reservation.PaymentStatus == GoReservationPaymentStatus.NotSatisfied;

        private static string CurrencySymbol => CultureInfo.CurrentCulture.NumberFormat.CurrencySymbol;

        private string ConfirmText => RefundState switch
        {
            ReservationRefundState.Available => $"{Localize(nameof(Autogenerated.Resources.GO_RESERVATIONS_CANCEL_CONFIRM))} {Localize(nameof(Autogenerated.Resources.GO_RESERVATIONS_CANCEL_REFUND))}",
            ReservationRefundState.Expired => $"{Localize(nameof(Autogenerated.Resources.GO_RESERVATIONS_CANCEL_CONFIRM))} {Localize(nameof(Autogenerated.Resources.GO_RESERVATIONS_CANCEL_REFUND_EXPIRED))}",
            _ => Localize(nameof(Autogenerated.Resources.GO_RESERVATIONS_CANCEL_CONFIRM))
        };

        private string Localize(string key) => LocalizationService.GetString(key);
    }
}
