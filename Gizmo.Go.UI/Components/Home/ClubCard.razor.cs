using Gizmo.Go.Core.Models.Branch;
using Gizmo.Go.UI.Helpers;
using Gizmo.UI.Services;
using Microsoft.AspNetCore.Components;

namespace Gizmo.Go.UI.Components.Home
{
    /// <summary>
    /// Club card of the Home clubs list. The open state and the hours are hidden when the club has no business hours.
    /// </summary>
    public partial class ClubCard : ComponentBase
    {
        [Inject]
        private ILocalizationService LocalizationService { get; set; } = null!;

        [Parameter, EditorRequired]
        public Branch Club { get; set; } = null!;

        /// <summary>
        /// Raised with the club id when "Book" is tapped: the booking starts on the club page.
        /// </summary>
        [Parameter]
        public EventCallback<int> OnOpen { get; set; }

        private Task OpenAsync() => OnOpen.InvokeAsync(Club.Id);

        private bool? IsOpen => BranchScheduleHelper.IsOpen(Club, DateTime.UtcNow);

        private string HoursText =>
            BranchScheduleHelper.IsAroundTheClock(Club)
                ? LocalizationService.GetString(nameof(Autogenerated.Resources.GO_HOME_CLUB_AROUND_THE_CLOCK))
                : BranchScheduleHelper.FormatHours(Club) ?? string.Empty;
    }
}
