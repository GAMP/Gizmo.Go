using System.Globalization;
using Gizmo.Go.Core.Models.Reservation;
using Gizmo.UI.Services;
using Microsoft.AspNetCore.Components;

namespace Gizmo.Go.UI.Components.Home
{
    /// <summary>
    /// The nearest reservation of the user. The page shows the card only while it loads or when there is a reservation.
    /// </summary>
    public partial class NearestReservationCard : ComponentBase
    {
        [Inject]
        private ILocalizationService LocalizationService { get; set; } = null!;

        [Parameter]
        public NearestReservation? Reservation { get; set; }

        [Parameter]
        public bool IsLoading { get; set; }

        private string DayText
        {
            get
            {
                var days = (Reservation!.Start.Date - DateTime.Today).Days;

                return days switch
                {
                    0 => LocalizationService.GetString(nameof(Autogenerated.Resources.GO_HOME_TODAY)),
                    1 => LocalizationService.GetString(nameof(Autogenerated.Resources.GO_HOME_TOMORROW)),
                    _ => Reservation.Start.ToString("d MMMM", CultureInfo.CurrentCulture)
                };
            }
        }

        private string TimeText => $"{Reservation!.Start:HH:mm} - {Reservation.End:HH:mm}";

        private string StatusText => LocalizationService.GetString(Reservation!.Status == NearestReservationStatus.Active
            ? nameof(Autogenerated.Resources.GO_HOME_RESERVATION_ACTIVE)
            : nameof(Autogenerated.Resources.GO_HOME_RESERVATION_CONFIRMED));
    }
}
