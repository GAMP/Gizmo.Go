using System.Globalization;
using Gizmo.Go.Core.Models.News;
using Gizmo.Go.UI.Helpers;
using Gizmo.UI.Services;
using Microsoft.AspNetCore.Components;

namespace Gizmo.Go.UI.Components.Home
{
    /// <summary>
    /// News card of the Home carousel and of the news list.
    /// </summary>
    public partial class NewsCard : ComponentBase
    {
        public enum NewsCardVariant { Carousel, List }

        // carousel card accents (violet, blue, orange), repeated by position
        private const int CarouselAccentCount = 3;

        [Inject]
        private ILocalizationService LocalizationService { get; set; } = null!;

        [Parameter, EditorRequired]
        public NewsItem Item { get; set; } = null!;

        [Parameter]
        public NewsCardVariant Variant { get; set; } = NewsCardVariant.Carousel;

        /// <summary>
        /// Gets or sets the position of the card in the carousel; it picks the accent color.
        /// </summary>
        [Parameter]
        public int Index { get; set; }

        [Parameter]
        public EventCallback<int> OnClick { get; set; }

        private bool IsList => Variant == NewsCardVariant.List;

        private string VariantClass => IsList
            ? "news-card--list"
            : $"news-card--carousel news-card--accent-{Index % CarouselAccentCount}";

        private string PlainText => HtmlTextHelper.ToPlainText(Item.Body);

        private string Caption
        {
            get
            {
                var club = Item.BranchName ?? LocalizationService.GetString(nameof(Autogenerated.Resources.GO_HOME_NEWS_ALL_CLUBS));
                return Item.Date is { } date
                    ? $"{date.ToString("d MMM yyyy", CultureInfo.CurrentCulture)} · {club}"
                    : club;
            }
        }

        private Task OnClickAsync() => OnClick.InvokeAsync(Item.Id);
    }
}
