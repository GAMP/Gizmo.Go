using Gizmo.UI.Services;
using Microsoft.AspNetCore.Components;

namespace Gizmo.Go.UI.Components.Home
{
    /// <summary>
    /// City selector of the clubs list: "All cities" and the cities of the clubs. Without cities it is a plain "All cities"
    /// label without the dropdown.
    /// </summary>
    public partial class CitySelect : ComponentBase
    {
        // purely visual state of the dropdown
        private bool _open;

        [Inject]
        private ILocalizationService LocalizationService { get; set; } = null!;

        [Parameter]
        public IReadOnlyList<string> Cities { get; set; } = [];

        /// <summary>
        /// Gets or sets the selected city; null means all cities.
        /// </summary>
        [Parameter]
        public string? SelectedCity { get; set; }

        [Parameter]
        public EventCallback<string?> OnSelect { get; set; }

        private string AllCitiesText => LocalizationService.GetString(nameof(Autogenerated.Resources.GO_HOME_ALL_CITIES));

        private string SelectedText => SelectedCity ?? AllCitiesText;

        private void Toggle() => _open = !_open;

        private async Task SelectAsync(string? city)
        {
            _open = false;
            await OnSelect.InvokeAsync(city);
        }
    }
}
