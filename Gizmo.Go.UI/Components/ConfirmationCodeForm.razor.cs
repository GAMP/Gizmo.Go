using Gizmo.UI.Services;
using Microsoft.AspNetCore.Components;

namespace Gizmo.Go.UI.Components
{
    /// <summary>
    /// Confirmation code step shared by registration and password recovery (phone and email):
    /// title, subtitle, code cells, resend / change links, hint with the code lifetime and the submit button.
    /// Figma 159:13381.
    /// </summary>
    public partial class ConfirmationCodeForm : ComponentBase
    {
        [Inject] private ILocalizationService LocalizationService { get; set; } = null!;

        /// <summary>
        /// The code was sent by email (otherwise to a phone): title, change link and hint follow it.
        /// </summary>
        [Parameter] public bool IsEmail { get; set; }

        /// <summary>
        /// Text under the title (who the code was sent to).
        /// </summary>
        [Parameter] public RenderFragment? Subtitle { get; set; }

        [Parameter] public string? ErrorMessage { get; set; }

        [Parameter] public string[] Digits { get; set; } = [];
        [Parameter] public EventCallback<(int Index, string Value)> OnDigitChanged { get; set; }
        [Parameter] public EventCallback<int> OnDigitCleared { get; set; }

        [Parameter] public int SecondsLeft { get; set; }
        [Parameter] public EventCallback OnResend { get; set; }
        [Parameter] public EventCallback OnChange { get; set; }

        /// <summary>
        /// Code lifetime from the server (start result ExpiresInSeconds), in minutes; 0 hides the sentence.
        /// </summary>
        [Parameter] public int CodeLifetimeMinutes { get; set; }

        [Parameter] public bool CanSubmit { get; set; }
        [Parameter] public bool IsLoading { get; set; }
        [Parameter] public EventCallback OnConfirm { get; set; }

        private bool TimerExpired => SecondsLeft <= 0;

        private string Title => LocalizationService.GetString(IsEmail
            ? nameof(Autogenerated.Resources.GO_CONFIRMATION_HEADING_EMAIL)
            : nameof(Autogenerated.Resources.GO_CONFIRMATION_HEADING_PHONE));

        private string ChangeText => LocalizationService.GetString(IsEmail
            ? nameof(Autogenerated.Resources.GO_REGISTRATION_EMAIL_CONFIRMATION_CHANGE_EMAIL)
            : nameof(Autogenerated.Resources.GO_CONFIRMATION_CHANGE_NUMBER));

        private string Hint
        {
            get
            {
                var hint = LocalizationService.GetString(IsEmail
                    ? nameof(Autogenerated.Resources.GO_REGISTRATION_EMAIL_CONFIRMATION_HINT)
                    : nameof(Autogenerated.Resources.GO_CONFIRMATION_HINT));

                return CodeLifetimeMinutes > 0
                    ? LocalizationService.GetString(nameof(Autogenerated.Resources.GO_CONFIRMATION_CODE_LIFETIME), CodeLifetimeMinutes) + " " + hint
                    : hint;
            }
        }
    }
}
