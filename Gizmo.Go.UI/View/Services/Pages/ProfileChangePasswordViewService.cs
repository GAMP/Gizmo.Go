using System.Text.RegularExpressions;
using Gizmo.Go.Core.Models.Profile;
using Gizmo.Go.Core.Services;
using Gizmo.Go.UI.Helpers;
using Gizmo.Go.UI.View.States;
using Gizmo.Go.UI.View.States.Pages;
using Gizmo.UI;
using Gizmo.UI.Services;
using Gizmo.UI.View.Services;
using Microsoft.AspNetCore.Components;
using Microsoft.AspNetCore.Components.Forms;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Logging;

namespace Gizmo.Go.UI.View.Services.Pages
{
    /// <summary>
    /// Change password screen of the logged in user: the current password and the new one with the server password rules.
    /// </summary>
    /// <remarks>
    /// The rules checklist is the logic of the password recovery new-password step (a client copy that is not shared).
    /// </remarks>
    [Register]
    [Route(NavigationHelper.ProfileChangePasswordRoute)]
    public sealed class ProfileChangePasswordViewService : ValidatingViewStateServiceBase<ProfileChangePasswordViewState>
    {
        private readonly IUserProfileService _userProfileService;
        private readonly ILocalizationService _localizationService;
        private readonly IMobileOptionsService _mobileOptionsService;
        private readonly NavigationService _navigationService;
        private bool _passwordRulesLoaded;

        public ProfileChangePasswordViewService(
            ProfileChangePasswordViewState viewState,
            ILogger<ProfileChangePasswordViewService> logger,
            IServiceProvider serviceProvider,
            IUserProfileService userProfileService,
            ILocalizationService localizationService,
            IMobileOptionsService mobileOptionsService,
            NavigationService navigationService) : base(viewState, logger, serviceProvider)
        {
            _userProfileService = userProfileService;
            _localizationService = localizationService;
            _mobileOptionsService = mobileOptionsService;
            _navigationService = navigationService;
        }

        public void SetCurrentPassword(string value)
        {
            ViewState.CurrentPassword = value;
            ValidateProperty(() => ViewState.CurrentPassword);
        }

        public void SetNewPassword(string value)
        {
            ViewState.NewPassword = value;
            CheckPasswordRules(ViewState.NewPassword);
            ValidateProperty(() => ViewState.NewPassword);
        }

        public void SetRepeatPassword(string value)
        {
            ViewState.RepeatPassword = value;
            ValidateProperty(() => ViewState.RepeatPassword);
        }

        public async Task SubmitAsync()
        {
            if (ViewState.IsLoading)
                return;

            Validate();

            if (ViewState.IsValid != true)
                return;

            ViewState.IsLoading = true;
            ViewState.HasError = false;
            ViewState.ErrorMessage = string.Empty;
            ViewState.RaiseChanged();

            try
            {
                var result = await _userProfileService.ChangePasswordAsync(ViewState.CurrentPassword, ViewState.NewPassword);

                switch (result)
                {
                    case UserPasswordChangeCode.Success:
                        ViewState.IsSuccess = true;
                        break;
                    case UserPasswordChangeCode.WrongPassword:
                        AddError(() => ViewState.CurrentPassword, _localizationService.GetString(nameof(Autogenerated.Resources.GO_PROFILE_CHANGE_PASSWORD_WRONG)));
                        break;
                    default:
                        AddError(() => ViewState.NewPassword, _localizationService.GetString(nameof(Autogenerated.Resources.GO_PROFILE_CHANGE_PASSWORD_INVALID)));
                        break;
                }
            }
            catch (Exception ex)
            {
                Logger.LogError(ex, "Change password error.");
                ViewState.HasError = true;
                ViewState.ErrorMessage = _localizationService.GetString(nameof(Autogenerated.Resources.GO_GEN_AN_ERROR_HAS_OCCURRED));
            }
            finally
            {
                ViewState.IsLoading = false;
                ViewState.RaiseChanged();
            }
        }

        /// <summary>
        /// Returns to the previous screen; an entry opened directly (without an app history) opens the profile.
        /// </summary>
        /// <param name="historyEntryState">History entry state of the current screen.</param>
        public Task BackAsync(string? historyEntryState) => _navigationService.GoBackOrNavigateAsync(historyEntryState, NavigationHelper.ProfileRoute);

        /// <summary>
        /// Opens the profile after the success screen (replaces the entry, a back step does not return to the form).
        /// </summary>
        public void Done() => _navigationService.NavigateTo(NavigationHelper.ProfileRoute, new NavigationOptions { ReplaceHistoryEntry = true });

        public void Clear()
        {
            ViewState.CurrentPassword = string.Empty;
            ViewState.NewPassword = string.Empty;
            ViewState.RepeatPassword = string.Empty;
            ViewState.IsLoading = false;
            ViewState.HasError = false;
            ViewState.IsSuccess = false;
            ViewState.ErrorMessage = string.Empty;
            CheckPasswordRules(ViewState.NewPassword);
            ResetValidationState();
            DebounceViewStateChanged();
        }

        /// <summary>
        /// Loads the password rules when the screen was opened without a navigation event (a direct url); does nothing once
        /// they are loaded.
        /// </summary>
        public Task EnsurePasswordRulesLoadedAsync() => TryEnsurePasswordRulesAsync(default);

        protected override async Task OnNavigatedIn(NavigationParameters navigationParameters, CancellationToken cancellationToken = default)
        {
            await TryEnsurePasswordRulesAsync(cancellationToken);

            Clear();
        }

        // the password rules come from the server mobile options, loaded on the page entry
        // (not in OnInitializing: the view services are initialized one by one on start, an unreachable server would block it)
        private async Task EnsurePasswordRulesAsync(CancellationToken ct)
        {
            if (_passwordRulesLoaded)
                return;

            var passwordValidation = (await _mobileOptionsService.GetAsync(ct)).PasswordValidation;

            ViewState.PasswordTooltip.MinimumLengthRule = passwordValidation.MinimumLength;
            ViewState.PasswordTooltip.MaximumLengthRule = passwordValidation.MaximumLength;
            ViewState.PasswordTooltip.HasLowerCaseCharactersRule = passwordValidation.LowerCaseCharactersRequired;
            ViewState.PasswordTooltip.HasUpperCaseCharactersRule = passwordValidation.UpperCaseCharactersRequired;
            ViewState.PasswordTooltip.HasNumbersRule = passwordValidation.NumbersRequired;

            ViewState.PasswordTooltip.TotalRules = 0;

            if (ViewState.PasswordTooltip.MinimumLengthRule > 0 || ViewState.PasswordTooltip.MaximumLengthRule > 0)
                ViewState.PasswordTooltip.TotalRules += 1;

            if (ViewState.PasswordTooltip.HasLowerCaseCharactersRule)
                ViewState.PasswordTooltip.TotalRules += 1;

            if (ViewState.PasswordTooltip.HasUpperCaseCharactersRule)
                ViewState.PasswordTooltip.TotalRules += 1;

            if (ViewState.PasswordTooltip.HasNumbersRule)
                ViewState.PasswordTooltip.TotalRules += 1;

            CheckPasswordRules(ViewState.NewPassword);

            ViewState.PasswordTooltip.RaiseChanged();

            _passwordRulesLoaded = true;
        }

        // without the rules the checklist is not shown and the server validates the new password
        private async Task TryEnsurePasswordRulesAsync(CancellationToken ct)
        {
            try
            {
                await EnsurePasswordRulesAsync(ct);
            }
            catch (Exception ex) when (ex is not OperationCanceledException)
            {
                Logger.LogError(ex, "Could not load the password rules.");
            }
        }

        protected override void OnValidate(FieldIdentifier fieldIdentifier, ValidationTrigger validationTrigger)
        {
            if (fieldIdentifier.FieldEquals(() => ViewState.NewPassword) || fieldIdentifier.FieldEquals(() => ViewState.RepeatPassword))
            {
                if (fieldIdentifier.FieldEquals(() => ViewState.NewPassword))
                {
                    if (ViewState.PasswordTooltip.PassedRules < ViewState.PasswordTooltip.TotalRules)
                    {
                        AddError(() => ViewState.NewPassword, ViewState.PasswordTooltip.ErrorMessage);
                    }
                }

                ClearError(() => ViewState.RepeatPassword);
                if (!string.IsNullOrEmpty(ViewState.NewPassword) && !string.IsNullOrEmpty(ViewState.RepeatPassword) && string.Compare(ViewState.NewPassword, ViewState.RepeatPassword) != 0)
                {
                    AddError(() => ViewState.RepeatPassword, _localizationService.GetString(nameof(Autogenerated.Resources.GO_GEN_PASSWORDS_DO_NOT_MATCH)));
                }
            }
        }

        private void CheckPasswordRules(string password)
        {
            ViewState.PasswordTooltip.PassedRules = 0;
            ViewState.PasswordTooltip.ErrorMessage = _localizationService.GetString(nameof(Autogenerated.Resources.GO_PASSWORD_MESSAGE_TOO_SHORT));

            ViewState.PasswordTooltip.LengthRulePassed = false;
            ViewState.PasswordTooltip.LowerCaseCharactersRulePassed = false;
            ViewState.PasswordTooltip.UpperCaseCharactersRulePassed = false;
            ViewState.PasswordTooltip.NumbersRulePassed = false;

            if (string.IsNullOrEmpty(password))
                return;

            if (ViewState.PasswordTooltip.MinimumLengthRule > 0 || ViewState.PasswordTooltip.MaximumLengthRule > 0)
            {
                if ((!ViewState.PasswordTooltip.MinimumLengthRule.HasValue || password.Length >= ViewState.PasswordTooltip.MinimumLengthRule) &&
                    (!ViewState.PasswordTooltip.MaximumLengthRule.HasValue || password.Length <= ViewState.PasswordTooltip.MaximumLengthRule))
                {
                    ViewState.PasswordTooltip.PassedRules += 1;
                    ViewState.PasswordTooltip.LengthRulePassed = true;
                }
                else
                {
                    if (ViewState.PasswordTooltip.MaximumLengthRule.HasValue && password.Length >= ViewState.PasswordTooltip.MaximumLengthRule)
                    {
                        ViewState.PasswordTooltip.ErrorMessage = _localizationService.GetString(nameof(Autogenerated.Resources.GO_PASSWORD_MESSAGE_TOO_LONG));
                    }
                    else
                    {
                        ViewState.PasswordTooltip.ErrorMessage = _localizationService.GetString(nameof(Autogenerated.Resources.GO_PASSWORD_MESSAGE_TOO_SHORT));
                    }
                }
            }

            if (ViewState.PasswordTooltip.HasLowerCaseCharactersRule)
            {
                if (Regex.IsMatch(password, "\\p{Ll}"))
                {
                    ViewState.PasswordTooltip.PassedRules += 1;
                    ViewState.PasswordTooltip.LowerCaseCharactersRulePassed = true;
                }
                else
                {
                    ViewState.PasswordTooltip.ErrorMessage = _localizationService.GetString(nameof(Autogenerated.Resources.GO_PASSWORD_MESSAGE_TOO_EASY));
                }
            }

            if (ViewState.PasswordTooltip.HasUpperCaseCharactersRule)
            {
                if (Regex.IsMatch(password, "\\p{Lu}"))
                {
                    ViewState.PasswordTooltip.PassedRules += 1;
                    ViewState.PasswordTooltip.UpperCaseCharactersRulePassed = true;
                }
                else
                {
                    ViewState.PasswordTooltip.ErrorMessage = _localizationService.GetString(nameof(Autogenerated.Resources.GO_PASSWORD_MESSAGE_TOO_EASY));
                }
            }

            if (ViewState.PasswordTooltip.HasNumbersRule)
            {
                if (Regex.IsMatch(password, "[0-9]"))
                {
                    ViewState.PasswordTooltip.PassedRules += 1;
                    ViewState.PasswordTooltip.NumbersRulePassed = true;
                }
                else
                {
                    ViewState.PasswordTooltip.ErrorMessage = _localizationService.GetString(nameof(Autogenerated.Resources.GO_PASSWORD_MESSAGE_TOO_EASY));
                }
            }

            if (ViewState.PasswordTooltip.PassedRules == ViewState.PasswordTooltip.TotalRules)
            {
                ViewState.PasswordTooltip.ErrorMessage = _localizationService.GetString(nameof(Autogenerated.Resources.GO_PASSWORD_MESSAGE_SECURE));
            }
        }
    }
}
