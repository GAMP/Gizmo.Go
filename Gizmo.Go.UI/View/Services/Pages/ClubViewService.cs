using Gizmo.Go.Core.Services;
using Gizmo.Go.UI.Helpers;
using Gizmo.Go.UI.Services.Dialog;
using Gizmo.Go.UI.View.States.Pages;
using Gizmo.UI;
using Gizmo.UI.Services;
using Gizmo.UI.View.Services;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Logging;

namespace Gizmo.Go.UI.View.Services.Pages
{
    /// <summary>
    /// Club page. The route has a parameter (<see cref="NavigationHelper.ClubRoute"/>), which the navigation events of
    /// the view services do not match, so the page starts the load with the id from the route.
    /// </summary>
    [Register()]
    public sealed class ClubViewService : ViewStateServiceBase<ClubViewState>
    {
        private readonly IBranchProvider _branchProvider;
        private readonly IExternalLauncher _externalLauncher;
        private readonly IGizmoGoDialogService _dialogService;
        private readonly ILocalizationService _localizationService;
        private readonly NavigationService _navigationService;

        private CancellationTokenSource? _loadCts;

        public ClubViewService(
            ClubViewState viewState,
            ILogger<ClubViewService> logger,
            IServiceProvider serviceProvider,
            IBranchProvider branchProvider,
            IExternalLauncher externalLauncher,
            IGizmoGoDialogService dialogService,
            ILocalizationService localizationService,
            NavigationService navigationService) : base(viewState, logger, serviceProvider)
        {
            _branchProvider = branchProvider;
            _externalLauncher = externalLauncher;
            _dialogService = dialogService;
            _localizationService = localizationService;
            _navigationService = navigationService;
        }

        public async Task LoadAsync(int id)
        {
            CancelLoad();

            var cts = _loadCts = new CancellationTokenSource();
            ViewState.Details.Reset();
            ViewState.IsNotFound = false;
            ViewState.IsScheduleExpanded = false;
            RaiseViewStateChanged();

            await ViewState.Details.LoadAsync(ct => _branchProvider.GetDetailsAsync(id, ct), Logger, "club details", RaiseViewStateChanged, cts.Token);

            if (cts.IsCancellationRequested)
                return;

            ViewState.IsNotFound = !ViewState.Details.HasError && ViewState.Details.Value is null;
            RaiseViewStateChanged();
        }

        /// <summary>
        /// Cancels the running load (the page is left).
        /// </summary>
        public void CancelLoad()
        {
            _loadCts?.Cancel();
            _loadCts = null;
        }

        public void ToggleSchedule()
        {
            ViewState.IsScheduleExpanded = !ViewState.IsScheduleExpanded;
            RaiseViewStateChanged();
        }

        /// <summary>
        /// Opens the system dialer with the club phone.
        /// </summary>
        public async Task CallAsync()
        {
            if (ViewState.Details.Value?.Branch.Phone is not { Length: > 0 } phone)
                return;

            try
            {
                await _externalLauncher.OpenAsync("tel:" + string.Concat(phone.Where(c => !char.IsWhiteSpace(c))));
            }
            catch (Exception ex)
            {
                Logger.LogError(ex, "Cannot open the dialer.");
            }
        }

        public Task ShowClubRulesAsync() => ShowRulesAsync(nameof(Autogenerated.Resources.GO_CLUB_RULES_CLUB));

        public Task ShowBookingRulesAsync() => ShowRulesAsync(nameof(Autogenerated.Resources.GO_CLUB_RULES_BOOKING));

        /// <summary>
        /// Returns to the previous screen; an entry opened directly (without an app history) opens Home.
        /// </summary>
        /// <param name="historyEntryState">History entry state of the current screen.</param>
        public Task BackAsync(string? historyEntryState) => _navigationService.GoBackOrNavigateAsync(historyEntryState, NavigationHelper.HomePage);

        private async Task ShowRulesAsync(string titleKey)
        {
            try
            {
                await _dialogService.ShowRulesDialogAsync(_localizationService.GetString(titleKey));
            }
            catch (Exception ex)
            {
                Logger.LogError(ex, "Cannot show the rules dialog.");
            }
        }
    }
}
