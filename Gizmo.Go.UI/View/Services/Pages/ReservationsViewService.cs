using Gizmo.Go.Core.Models.Notification;
using Gizmo.Go.Core.Models.Reservation;
using Gizmo.Go.Core.Services;
using Gizmo.Go.Core.Services.Notification;
using Gizmo.Go.UI.Helpers;
using Gizmo.Go.UI.View.States.Pages;
using Gizmo.UI;
using Gizmo.UI.Services;
using Gizmo.UI.View.Services;
using Microsoft.AspNetCore.Components;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Logging;

namespace Gizmo.Go.UI.View.Services.Pages
{
    /// <summary>
    /// "My reservations": current / upcoming and completed reservations, details, cancel of an owned reservation.
    /// The completed list is the latest <see cref="CompletedLimit"/> items (no paging yet).
    /// </summary>
    [Register()]
    [Route(NavigationHelper.ReservationsRoute)]
    public sealed class ReservationsViewService : ViewStateServiceBase<ReservationsViewState>
    {
        private const int CompletedLimit = 10;

        private readonly IAuthService _authService;
        private readonly IReservationService _reservationService;
        private readonly IGizmoGoNotificationsService _notificationsService;
        private readonly ILocalizationService _localizationService;
        private readonly NavigationService _navigationService;

        private CancellationTokenSource? _loadCts;

        public ReservationsViewService(
            ReservationsViewState viewState,
            ILogger<ReservationsViewService> logger,
            IServiceProvider serviceProvider,
            IAuthService authService,
            IReservationService reservationService,
            IGizmoGoNotificationsService notificationsService,
            ILocalizationService localizationService,
            NavigationService navigationService) : base(viewState, logger, serviceProvider)
        {
            _authService = authService;
            _reservationService = reservationService;
            _notificationsService = notificationsService;
            _localizationService = localizationService;
            _navigationService = navigationService;
        }

        /// <summary>
        /// Loads the reservations when the screen was opened without a navigation event (a direct url).
        /// </summary>
        public Task EnsureLoadedAsync() => _loadCts is null ? LoadAsync() : Task.CompletedTask;

        public Task LoadAsync()
        {
            ResetPage();
            return LoadBlocksAsync();
        }

        /// <summary>
        /// Sets what the page shows: the reservation with the id (the nearest one when <paramref name="isNearest"/>) or the full list.
        /// </summary>
        public void SetView(int? id, bool isNearest)
        {
            if (ViewState.SingleId == id && ViewState.IsNearest == isNearest)
                return;

            ViewState.SingleId = id;
            ViewState.IsNearest = isNearest;
            RaiseViewStateChanged();
        }

        public Task RetryCurrentAsync() => LoadCurrentAsync(GetLoadToken());

        public Task RetryCompletedAsync() => LoadCompletedAsync(GetLoadToken());

        public void ToggleDetails(int id)
        {
            if (!ViewState.ExpandedIdSet.Add(id))
                ViewState.ExpandedIdSet.Remove(id);

            RaiseViewStateChanged();
        }

        public void ToggleCompleted()
        {
            ViewState.IsCompletedCollapsed = !ViewState.IsCompletedCollapsed;
            RaiseViewStateChanged();
        }

        public void RequestCancel(int id)
        {
            if (ViewState.IsCanceling)
                return;

            ViewState.ConfirmingCancelId = id;
            RaiseViewStateChanged();
        }

        public void KeepReservation()
        {
            if (ViewState.IsCanceling)
                return;

            ViewState.ConfirmingCancelId = null;
            RaiseViewStateChanged();
        }

        public async Task ConfirmCancelAsync()
        {
            if (ViewState.IsCanceling || ViewState.ConfirmingCancelId is not { } id)
                return;

            ViewState.IsCanceling = true;
            RaiseViewStateChanged();

            // canceled when the screen is left or reloaded while the request runs, then there is nothing to reload
            var pageToken = GetLoadToken();
            var reload = false;

            try
            {
                var result = await _reservationService.CancelAsync(id);

                ViewState.ConfirmingCancelId = null;
                reload = true;

                if (result == ReservationCancelResult.NotAvailable)
                    await _notificationsService.ShowAsync(_localizationService.GetString(nameof(Autogenerated.Resources.GO_RESERVATIONS_CANCEL_NOT_AVAILABLE)), GoNotificationType.Warning);
            }
            catch (Exception ex)
            {
                Logger.LogError(ex, "Cannot cancel the reservation {ReservationId}.", id);
                await _notificationsService.ShowAsync(_localizationService.GetString(nameof(Autogenerated.Resources.GO_GEN_AN_ERROR_HAS_OCCURRED)), GoNotificationType.Error);
            }
            finally
            {
                ViewState.IsCanceling = false;
                RaiseViewStateChanged();
            }

            if (reload && !pageToken.IsCancellationRequested)
                await ReloadAsync();
        }

        /// <summary>
        /// Returns to the previous screen; an entry opened directly (without an app history) opens Home.
        /// </summary>
        /// <param name="historyEntryState">History entry state of the current screen.</param>
        public Task BackAsync(string? historyEntryState) => _navigationService.GoBackOrNavigateAsync(historyEntryState, NavigationHelper.HomePage);

        protected override Task OnNavigatedIn(NavigationParameters navigationParameters, CancellationToken cancellationToken = default)
        {
            // an unauthenticated user is redirected to Welcome by the page, there is nothing to load
            if (_authService.State != AuthState.Authenticated)
                return Task.CompletedTask;

            return LoadAsync();
        }

        protected override Task OnNavigatedOut(NavigationParameters navigationParameters, CancellationToken cancellationToken = default)
        {
            CancelLoad();
            return base.OnNavigatedOut(navigationParameters, cancellationToken);
        }

        private void ResetPage()
        {
            CancelLoad();

            ViewState.Current.Reset();
            ViewState.Completed.Reset();
            ViewState.IsCompletedCollapsed = false;
            ViewState.ExpandedIdSet.Clear();
            ViewState.ConfirmingCancelId = null;
            ViewState.IsCanceling = false;
            ViewState.IsReloading = false;
        }

        // the loaded lists stay on screen until the new result arrives
        private async Task ReloadAsync()
        {
            CancelLoad();

            var cancellationToken = GetLoadToken();
            ViewState.IsReloading = true;

            await LoadBlocksAsync();

            // a newer load owns the flag
            if (cancellationToken.IsCancellationRequested)
                return;

            ViewState.IsReloading = false;
            RaiseViewStateChanged();
        }

        private async Task LoadBlocksAsync()
        {
            var cancellationToken = GetLoadToken();

            RaiseViewStateChanged();

            await Task.WhenAll(LoadCurrentAsync(cancellationToken), LoadCompletedAsync(cancellationToken));
        }

        private Task LoadCurrentAsync(CancellationToken cancellationToken) =>
            ViewState.Current.LoadAsync(ct => _reservationService.GetCurrentAsync(ct)!, Logger, "current reservations", RaiseViewStateChanged, cancellationToken);

        private Task LoadCompletedAsync(CancellationToken cancellationToken) =>
            ViewState.Completed.LoadAsync(ct => _reservationService.GetCompletedAsync(CompletedLimit, ct)!, Logger, "completed reservations", RaiseViewStateChanged, cancellationToken);

        private CancellationToken GetLoadToken() => (_loadCts ??= new CancellationTokenSource()).Token;

        private void CancelLoad()
        {
            _loadCts?.Cancel();
            _loadCts = null;
        }
    }
}
