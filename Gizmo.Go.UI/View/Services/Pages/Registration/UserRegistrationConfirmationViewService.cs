using Gizmo.Go.Core.Models.Registration;
using Gizmo.Go.Core.Services;
using Gizmo.Go.UI.Helpers;
using Gizmo.Go.UI.Services.Registration;
using Gizmo.Go.UI.View.States.Pages.Registration;
using Gizmo.UI.Services;
using Gizmo.UI.View.Services;
using Gizmo.UI;
using Microsoft.AspNetCore.Components.Forms;
using Microsoft.AspNetCore.Components;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Logging;

namespace Gizmo.Go.UI.View.Services.Pages.Registration
{
    [Register()]
    [Route(NavigationHelper.RegistrationConfirmationRoute)]
    public sealed class UserRegistrationConfirmationViewService : ValidatingViewStateServiceBase<UserRegistrationConfirmationViewState>
    {
        public UserRegistrationConfirmationViewService(
            UserRegistrationConfirmationViewState viewState,
            ILogger<UserRegistrationConfirmationViewService> logger,
            IServiceProvider serviceProvider,
            ILocalizationService localizationService,
            IUserRegistrationService registrationService,
            IRegistrationSessionService registrationSession) : base(viewState, logger, serviceProvider)
        {
            _localizationService = localizationService;
            _registrationService = registrationService;
            _registrationSession = registrationSession;
        }

        private readonly ILocalizationService _localizationService;
        private readonly IUserRegistrationService _registrationService;
        private readonly IRegistrationSessionService _registrationSession;
        private readonly CountdownTimer _timer = new();

        public void SetConfirmationCode(string value)
        {
            ViewState.ConfirmationCode = value;
            ValidateProperty(() => ViewState.ConfirmationCode);
        }

        public ValueTask SetDigitAsync(int index, string raw)
        {
            if (index < 0 || index >= ViewState.Digits.Length)
                return ValueTask.CompletedTask;

            ViewState.Digits[index] = new string(raw.Where(char.IsLetterOrDigit).Take(1).ToArray());
            SetConfirmationCode(string.Concat(ViewState.Digits));
            ViewState.RaiseChanged();
            return ValueTask.CompletedTask;
        }

        public ValueTask ClearDigitAsync(int index)
        {
            if (index < 0 || index >= ViewState.Digits.Length)
                return ValueTask.CompletedTask;

            ViewState.Digits[index] = string.Empty;
            SetConfirmationCode(string.Concat(ViewState.Digits));
            ViewState.RaiseChanged();
            return ValueTask.CompletedTask;
        }

        public void Clear()
        {
            ViewState.ConfirmationCode = string.Empty;
            ViewState.Digits = CreateDigits(_registrationSession.CodeLength);
            ViewState.ConfirmationCodeMessage = string.Empty;
            ViewState.IsLoading = false;
            ViewState.HasError = false;
            ViewState.ErrorMessage = string.Empty;
            ResetValidationState();
            DebounceViewStateChanged();
        }

        public async Task Confirm()
        {
            ViewState.IsLoading = true;
            ViewState.HasError = false;
            ViewState.ErrorMessage = string.Empty;
            ViewState.RaiseChanged();

            Validate();

            if (ViewState.IsValid != true)
            {
                ViewState.IsLoading = false;
                ViewState.RaiseChanged();
                return;
            }

            try
            {
                var result = await _registrationService.ConfirmTokenAsync(
                    _registrationSession.Token,
                    ViewState.ConfirmationCode);

                switch (result)
                {
                    case RegistrationConfirmCode.Success:
                        NavigationService.NavigateTo(NavigationHelper.RegistrationBasicFieldsRoute);
                        break;

                    case RegistrationConfirmCode.InvalidToken:
                    case RegistrationConfirmCode.InvalidConfirmationCode:
                        ViewState.HasError = true;
                        ViewState.ErrorMessage = _localizationService.GetString(nameof(Gizmo.Go.UI.Autogenerated.Resources.GO_USER_CONFIRMATION_CONFIRMATION_CODE_IS_INVALID));
                        break;

                    default:
                        ViewState.HasError = true;
                        ViewState.ErrorMessage = _localizationService.GetString(nameof(Gizmo.Go.UI.Autogenerated.Resources.GO_GEN_AN_ERROR_HAS_OCCURRED));
                        break;
                }
            }
            catch (Exception ex)
            {
                Logger.LogError(ex, "Confirm token error.");
                ViewState.HasError = true;
                ViewState.ErrorMessage = _localizationService.GetString(nameof(Gizmo.Go.UI.Autogenerated.Resources.GO_GEN_AN_ERROR_HAS_OCCURRED));
            }
            finally
            {
                ViewState.IsLoading = false;
                ViewState.RaiseChanged();
            }
        }

        public void Reset()
        {
            ViewState.HasError = false;
            ViewState.ErrorMessage = string.Empty;
        }

        public Task NavigateBackAsync()
        {
            CancelTimer();
            NavigationService.NavigateTo(_registrationSession.Flow == RegistrationFlow.Email
                ? NavigationHelper.RegistrationEmailRoute
                : NavigationHelper.RegistrationPhoneRoute);
            return Task.CompletedTask;
        }

        private static string[] CreateDigits(int codeLength)
        {
            var digits = new string[codeLength > 0 ? codeLength : 6];
            Array.Fill(digits, string.Empty);
            return digits;
        }

        public async ValueTask RestartTimerAsync()
        {
            ViewState.HasError = false;
            ViewState.ErrorMessage = string.Empty;
            ViewState.RaiseChanged();

            try
            {
                var request = new RegistrationStartRequest
                {
                    MethodId = _registrationSession.SelectedProvider?.MethodId ?? 0,
                    Kind = _registrationSession.Flow == RegistrationFlow.Email
                        ? RegistrationStartKind.Email
                        : RegistrationStartKind.MobilePhone,
                    Value = _registrationSession.ActualContact,
                };

                var result = await _registrationService.StartAsync(request);

                if (result is RegistrationStartResult.CodeInputRequired r)
                {
                    _registrationSession.SetStartResult(
                        r.Token,
                        r.Destination ?? _registrationSession.Destination,
                        r.CodeLength,
                        r.ExpiresInSeconds,
                        _registrationSession.Flow);
                    _ = StartTimerAsync();
                }
                else
                {
                    ViewState.HasError = true;
                    ViewState.ErrorMessage = _localizationService.GetString(nameof(Gizmo.Go.UI.Autogenerated.Resources.GO_GEN_AN_ERROR_HAS_OCCURRED));
                    ViewState.RaiseChanged();
                }
            }
            catch (Exception ex)
            {
                Logger.LogError(ex, "Resend confirmation code error.");
                ViewState.HasError = true;
                ViewState.ErrorMessage = _localizationService.GetString(nameof(Gizmo.Go.UI.Autogenerated.Resources.GO_GEN_AN_ERROR_HAS_OCCURRED));
                ViewState.RaiseChanged();
            }
        }

        protected override Task OnNavigatedIn(NavigationParameters navigationParameters, CancellationToken cancellationToken = default)
        {
            if (string.IsNullOrEmpty(_registrationSession.Token))
            {
                NavigationService.NavigateTo(NavigationHelper.RegistrationProvidersRoute);
                return Task.CompletedTask;
            }

            ViewState.ConfirmationCodeMessage = _registrationSession.Flow == RegistrationFlow.Email
                ? _localizationService.GetString(nameof(Gizmo.Go.UI.Autogenerated.Resources.GO_USER_CONFIRMATION_EMAIL_MESSAGE), _registrationSession.Destination)
                : _localizationService.GetString(nameof(Gizmo.Go.UI.Autogenerated.Resources.GO_USER_CONFIRMATION_SMS_MESSAGE), _registrationSession.Destination);

            ViewState.ConfirmationCode = string.Empty;
            ViewState.Digits = CreateDigits(_registrationSession.CodeLength);
            ViewState.Destination = _registrationSession.Destination;
            ViewState.IsEmailFlow = _registrationSession.Flow == RegistrationFlow.Email;
            ViewState.IsLoading = false;
            ViewState.HasError = false;
            ViewState.ErrorMessage = string.Empty;
            ResetValidationState();
            ViewState.RaiseChanged();

            _ = StartTimerAsync();

            return Task.CompletedTask;
        }

        protected override Task OnNavigatedOut(NavigationParameters navigationParameters, CancellationToken cancellationToken = default)
        {
            CancelTimer();
            return base.OnNavigatedOut(navigationParameters, cancellationToken);
        }

        private Task StartTimerAsync()
        {
            const int seconds = 90;

            return _timer.StartAsync(seconds, secs =>
            {
                ViewState.SecondsLeft = secs;
                ViewState.RaiseChanged();
                return Task.CompletedTask;
            }, Logger);
        }

        private void CancelTimer() => _timer.Cancel();

        protected override void OnValidate(FieldIdentifier fieldIdentifier, ValidationTrigger validationTrigger)
        {
            if (fieldIdentifier.FieldEquals(() => ViewState.ConfirmationCode))
            {
                if (ViewState.ConfirmationCode.Length != _registrationSession.CodeLength)
                {
                    AddError(() => ViewState.ConfirmationCode, _localizationService.GetString(nameof(Gizmo.Go.UI.Autogenerated.Resources.GO_CONFIRMATION_CODE_LENGTH_ERROR), _registrationSession.CodeLength));
                }
            }
        }
    }
}
