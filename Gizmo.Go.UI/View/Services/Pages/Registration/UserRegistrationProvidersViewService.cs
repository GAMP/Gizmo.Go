using Gizmo.Extensibility;
using Gizmo.Go.Core.Services;
using Gizmo.Go.UI.Helpers;
using Gizmo.Go.UI.Services.Registration;
using Gizmo.Go.UI.View.States.Pages.Registration;
using Gizmo.UI.Services;
using Gizmo.UI.View.Services;
using Gizmo;
using Microsoft.AspNetCore.Components;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Logging;

namespace Gizmo.Go.UI.View.Services.Pages.Registration
{
    [Register()]
    [Route(NavigationHelper.RegistrationProvidersRoute)]
    public sealed class UserRegistrationProvidersViewService : ViewStateServiceBase<UserRegistrationProvidersViewState>
    {
        public UserRegistrationProvidersViewService(
            UserRegistrationProvidersViewState viewState,
            ILogger<UserRegistrationProvidersViewService> logger,
            IServiceProvider serviceProvider,
            IUserRegistrationService registrationService,
            IRegistrationSessionService registrationSession,
            ILocalizationService localizationService) : base(viewState, logger, serviceProvider)
        {
            _registrationService = registrationService;
            _registrationSession = registrationSession;
            _localizationService = localizationService;
        }

        private readonly IUserRegistrationService _registrationService;
        private readonly IRegistrationSessionService _registrationSession;
        private readonly ILocalizationService _localizationService;

        public Task SelectProviderAsync(int methodId)
        {
            var provider = ViewState.Providers.FirstOrDefault(p => p.MethodId == methodId);
            if (provider is null)
                return Task.CompletedTask;

            ViewState.HasError = false;
            ViewState.ErrorMessage = string.Empty;
            ViewState.FailedChannelGuid = null;
            ViewState.RaiseChanged();

            if (provider.CapabilityGuid == IntegrationCapabilities.VerificationRedirect)
            {
                _registrationSession.SetSelectedProvider(provider);
                NavigationService.NavigateTo(NavigationHelper.RegistrationRedirectRoute);
                return Task.CompletedTask;
            }

            _registrationSession.SetSelectedProvider(provider);

            if (provider.ChannelGuid == new Guid(CommunicationChannels.Email))
                NavigationService.NavigateTo(NavigationHelper.RegistrationEmailRoute);
            else
                NavigationService.NavigateTo(NavigationHelper.RegistrationPhoneRoute);

            return Task.CompletedTask;
        }

        // mobile deviation: the Index step re-runs agreements and forwards to providers again, so back leaves the flow
        public Task NavigateBackAsync()
        {
            NavigationService.NavigateTo(NavigationHelper.WelcomePage);
            return Task.CompletedTask;
        }

        public Task NavigateToLoginAsync()
        {
            NavigationService.NavigateTo(NavigationHelper.LoginPage);
            return Task.CompletedTask;
        }

        protected override async Task OnNavigatedIn(NavigationParameters navigationParameters, CancellationToken cancellationToken = default)
        {
            var failedChannelGuid = _registrationSession.FailedProviderChannelGuid;
            _registrationSession.SetFailedProviderChannelGuid(null);

            if (failedChannelGuid.HasValue)
            {
                ViewState.HasError = true;
                ViewState.ErrorMessage = _localizationService.GetString(nameof(Gizmo.Go.UI.Autogenerated.Resources.GO_REGISTRATION_PROVIDER_REDIRECT_NOT_IMPLEMENTED));
                ViewState.FailedChannelGuid = failedChannelGuid;
            }
            else
            {
                ViewState.HasError = false;
                ViewState.ErrorMessage = string.Empty;
                ViewState.FailedChannelGuid = null;
            }

            ViewState.ShowAllProviders = _registrationSession.ShowAllProviders;
            _registrationSession.SetShowAllProviders(false);
            ViewState.IsLoading = true;
            ViewState.RaiseChanged();

            try
            {
                var providers = await _registrationService.GetMethodsAsync(cancellationToken);
                ViewState.Providers = providers;
            }
            catch (Exception ex)
            {
                Logger.LogError(ex, "Failed to load registration providers.");
                ViewState.HasError = true;
            }
            finally
            {
                ViewState.IsLoading = false;
                ViewState.RaiseChanged();
            }
        }
    }
}
