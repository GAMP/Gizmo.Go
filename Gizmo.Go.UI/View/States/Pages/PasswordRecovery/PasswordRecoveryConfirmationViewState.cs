using System.ComponentModel.DataAnnotations;
using Gizmo.Go.Core.Models.PasswordRecovery;
using Gizmo.Go.UI.View.States;
using Gizmo.UI.View.States;
using Gizmo.UI;
using Microsoft.Extensions.DependencyInjection;

namespace Gizmo.Go.UI.View.States.Pages.PasswordRecovery
{
    [Register]
    public sealed class PasswordRecoveryConfirmationViewState : ValidatingViewStateBase
    {
        [ValidatingProperty]
        [Required(ErrorMessageResourceType = typeof(Gizmo.Go.UI.Autogenerated.Resources), ErrorMessageResourceName = "GO_GEN_VE_REQUIRED_FIELD")]
        public string ConfirmationCode { get; internal set; } = string.Empty;

        public string ConfirmationCodeMessage { get; internal set; } = string.Empty;

        /// <summary>
        /// Gets if the code was sent by email (selects the "change email" text and the spam hint).
        /// </summary>
        public bool IsEmailChannel { get; internal set; }

        public string[] Digits { get; internal set; } = [];

        public bool CanSubmit => Digits.Length > 0 && Digits.All(d => d.Length == 1);

        public PasswordRecoveryAction Action { get; internal set; }

        public string? RedirectUrl { get; internal set; }

        public string? CallPhoneNumber { get; internal set; }

        public bool IsQrExpired { get; internal set; }

        public int SecondsLeft { get; internal set; }

        public bool TimerExpired => SecondsLeft <= 0;

        /// <summary>
        /// Code lifetime in minutes (server ExpiresInSeconds, rounded up); 0 when unknown.
        /// </summary>
        public int CodeLifetimeMinutes { get; internal set; }

        public bool IsLoading { get; internal set; }

        public bool HasError { get; internal set; }

        public string ErrorMessage { get; internal set; } = string.Empty;
    }
}
