using System.ComponentModel.DataAnnotations;
using Gizmo.Go.Core.Models;
using Gizmo.Go.Core.Models.PhoneValidation;
using Gizmo.UI;
using Gizmo.UI.View.States;
using Microsoft.Extensions.DependencyInjection;

namespace Gizmo.Go.UI.View.States.Pages
{
    [Register()]
    public sealed class ProfileCompletionViewState : ValidatingViewStateBase
    {
        [ValidatingProperty()]
        [StringLength(45, ErrorMessageResourceType = typeof(Autogenerated.Resources), ErrorMessageResourceName = nameof(Autogenerated.Resources.GO_GEN_VE_MAX_LENGTH))]
        public string? FirstName { get; internal set; }

        [ValidatingProperty()]
        [StringLength(45, ErrorMessageResourceType = typeof(Autogenerated.Resources), ErrorMessageResourceName = nameof(Autogenerated.Resources.GO_GEN_VE_MAX_LENGTH))]
        public string? LastName { get; internal set; }

        [ValidatingProperty()]
        public DateTime? BirthDate { get; internal set; }

        [ValidatingProperty()]
        public UserSex Sex { get; internal set; }

        [ValidatingProperty(IsAsync = true)]
        [EmailNullEmptyValidation(ErrorMessageResourceType = typeof(Autogenerated.Resources), ErrorMessageResourceName = nameof(Autogenerated.Resources.GO_GEN_VE_INVALID_FIELD))]
        [StringLength(254, ErrorMessageResourceType = typeof(Autogenerated.Resources), ErrorMessageResourceName = nameof(Autogenerated.Resources.GO_GEN_VE_MAX_LENGTH))]
        public string? Email { get; internal set; }

        [ValidatingProperty(IsAsync = true)]
        public string? MobilePhone { get; internal set; }

        [ValidatingProperty()]
        public string? PhoneRegionCode { get; internal set; }

        [ValidatingProperty()]
        [StringLength(20, ErrorMessageResourceType = typeof(Autogenerated.Resources), ErrorMessageResourceName = nameof(Autogenerated.Resources.GO_GEN_VE_MAX_LENGTH))]
        public string? Phone { get; internal set; }

        [ValidatingProperty()]
        [StringLength(255, ErrorMessageResourceType = typeof(Autogenerated.Resources), ErrorMessageResourceName = nameof(Autogenerated.Resources.GO_GEN_VE_MAX_LENGTH))]
        public string? Address { get; internal set; }

        [ValidatingProperty()]
        [StringLength(45, ErrorMessageResourceType = typeof(Autogenerated.Resources), ErrorMessageResourceName = nameof(Autogenerated.Resources.GO_GEN_VE_MAX_LENGTH))]
        public string? City { get; internal set; }

        [ValidatingProperty()]
        [StringLength(20, ErrorMessageResourceType = typeof(Autogenerated.Resources), ErrorMessageResourceName = nameof(Autogenerated.Resources.GO_GEN_VE_MAX_LENGTH))]
        [RegularExpression("^[0-9]*$", ErrorMessageResourceType = typeof(Autogenerated.Resources), ErrorMessageResourceName = nameof(Autogenerated.Resources.GO_GEN_VE_INVALID_FIELD))]
        public string? PostCode { get; internal set; }

        [ValidatingProperty()]
        [StringLength(45, ErrorMessageResourceType = typeof(Autogenerated.Resources), ErrorMessageResourceName = nameof(Autogenerated.Resources.GO_GEN_VE_MAX_LENGTH))]
        public string? Country { get; internal set; }

        public bool ShowFirstName { get; internal set; }

        public bool ShowLastName { get; internal set; }

        public bool ShowBirthDate { get; internal set; }

        public bool ShowSex { get; internal set; }

        public bool ShowEmail { get; internal set; }

        public bool ShowMobilePhone { get; internal set; }

        public bool ShowPhone { get; internal set; }

        public bool ShowAddress { get; internal set; }

        public bool ShowCity { get; internal set; }

        public bool ShowPostCode { get; internal set; }

        public bool ShowCountry { get; internal set; }

        /// <summary>
        /// Gets if there is anything to complete (the step has been started and found missing fields).
        /// </summary>
        public bool IsShown { get; internal set; }

        public IReadOnlyList<PhoneCountry> PhoneCountries { get; internal set; } = Array.Empty<PhoneCountry>();

        /// <summary>
        /// Default phone country of the server (ISO 3166-1 alpha-2), preselected by the phone field.
        /// </summary>
        public string? DefaultPhoneRegionCode { get; internal set; }

        public bool IsLoading { get; internal set; }

        public bool HasError { get; internal set; }

        public string ErrorMessage { get; internal set; } = string.Empty;
    }
}
