using System.ComponentModel.DataAnnotations;
using Gizmo.Go.Core.Models.PhoneValidation;
using Gizmo.Go.Core.Models.Registration;
using Gizmo.Go.UI.View.States;
using Gizmo.UI.View.States;
using Gizmo.UI;
using Microsoft.Extensions.DependencyInjection;

namespace Gizmo.Go.UI.View.States.Pages.Registration
{
    [Register]
    public sealed class UserRegistrationBasicFieldsViewState : ValidatingViewStateBase
    {
        /// <summary>
        /// Gets or sets username.
        /// </summary>
        [ValidatingProperty(IsAsync = true)]
        [Required(ErrorMessageResourceType = typeof(Gizmo.Go.UI.Autogenerated.Resources), ErrorMessageResourceName = "GO_GEN_VE_REQUIRED_FIELD")]
        [FileInvalidCharactersValidation]
        [StringLength(30, ErrorMessageResourceType = typeof(Gizmo.Go.UI.Autogenerated.Resources), ErrorMessageResourceName = "GO_GEN_VE_MAX_LENGTH")]
        public string Username { get; internal set; } = string.Empty;

        /// <summary>
        /// Gets or sets new password.
        /// </summary>
        [ValidatingProperty()]
        [StringLength(24, ErrorMessageResourceType = typeof(Gizmo.Go.UI.Autogenerated.Resources), ErrorMessageResourceName = "GO_GEN_VE_MAX_LENGTH")]
        public string Password { get; internal set; } = string.Empty;

        /// <summary>
        /// Gets or sets repeat password.
        /// </summary>
        [ValidatingProperty()]
        [StringLength(24, ErrorMessageResourceType = typeof(Gizmo.Go.UI.Autogenerated.Resources), ErrorMessageResourceName = "GO_GEN_VE_MAX_LENGTH")]
        public string RepeatPassword { get; internal set; } = string.Empty;

        [ValidatingProperty()]
        [StringLength(45, ErrorMessageResourceType = typeof(Gizmo.Go.UI.Autogenerated.Resources), ErrorMessageResourceName = "GO_GEN_VE_MAX_LENGTH")]
        public string? FirstName { get; internal set; }

        [ValidatingProperty()]
        [StringLength(45, ErrorMessageResourceType = typeof(Gizmo.Go.UI.Autogenerated.Resources), ErrorMessageResourceName = "GO_GEN_VE_MAX_LENGTH")]
        public string? LastName { get; internal set; }

        [ValidatingProperty()]
        public DateTime? BirthDate { get; internal set; }

        [ValidatingProperty()]
        public UserSex Sex { get; internal set; }

        [ValidatingProperty(IsAsync = true)]
        [EmailNullEmptyValidation(ErrorMessageResourceType = typeof(Gizmo.Go.UI.Autogenerated.Resources), ErrorMessageResourceName = "GO_GEN_VE_INVALID_FIELD")]
        [StringLength(254, ErrorMessageResourceType = typeof(Gizmo.Go.UI.Autogenerated.Resources), ErrorMessageResourceName = "GO_GEN_VE_MAX_LENGTH")]
        public string? Email { get; internal set; }

        [ValidatingProperty(IsAsync = true)]
        public string? MobilePhone { get; internal set; }

        [ValidatingProperty()]
        [StringLength(20, ErrorMessageResourceType = typeof(Gizmo.Go.UI.Autogenerated.Resources), ErrorMessageResourceName = "GO_GEN_VE_MAX_LENGTH")]
        public string? Phone { get; internal set; }

        [ValidatingProperty()]
        public string? PhoneRegionCode { get; internal set; }

        public bool IsLoading { get; internal set; }

        /// <summary>
        /// Gets if the account step (password) is completed and the profile step is shown.
        /// </summary>
        public bool IsAccountStepCompleted { get; internal set; }

        public string VerifiedContact { get; internal set; } = string.Empty;

        public bool IsEmailVerified { get; internal set; }

        public bool ShowFirstName { get; internal set; }

        public bool ShowLastName { get; internal set; }

        public bool ShowBirthDate { get; internal set; }

        public bool ShowSex { get; internal set; }

        public bool ShowEmail { get; internal set; }

        public bool ShowMobilePhone { get; internal set; }

        public bool ShowPhone { get; internal set; }

        public IReadOnlyList<PhoneCountry> PhoneCountries { get; internal set; } = Array.Empty<PhoneCountry>();

        public bool HasError { get; internal set; }

        public string ErrorMessage { get; internal set; } = string.Empty;

        public PasswordTooltipViewState PasswordTooltip { get; internal set; } = new PasswordTooltipViewState();
    }
}
