using System.ComponentModel.DataAnnotations;
using Gizmo.Go.Core.Models.PhoneValidation;
using Gizmo.UI;
using Gizmo.UI.View.States;
using Microsoft.Extensions.DependencyInjection;

namespace Gizmo.Go.UI.View.States.Pages
{
    [Register()]
    public sealed class LoginViewState : ValidatingViewStateBase
    {
        /// <summary>
        /// Login identifier: nickname, or the phone digits (calling code + national number) on the phone tab.
        /// Async: the phone format is checked by the phone validation service.
        /// </summary>
        [ValidatingProperty(IsAsync = true)]
        [Required(ErrorMessageResourceType = typeof(Autogenerated.Resources), ErrorMessageResourceName = nameof(Autogenerated.Resources.GO_VE_REQUIRED))]
        public string Username { get; internal set; } = string.Empty;

        [ValidatingProperty()]
        [Required(ErrorMessageResourceType = typeof(Autogenerated.Resources), ErrorMessageResourceName = nameof(Autogenerated.Resources.GO_VE_REQUIRED))]
        public string Password { get; internal set; } = string.Empty;

        public IReadOnlyList<PhoneCountry> PhoneCountries { get; internal set; } = Array.Empty<PhoneCountry>();

        public string? PhoneRegionCode { get; internal set; }

        public string Phone { get; internal set; } = string.Empty;

        public bool IsLoading { get; internal set; }

        public string? ErrorMessage { get; internal set; }
    }
}
