using System.Globalization;
using Gizmo.Go.Core.Models.Reservation;
using Gizmo.UI.Services;

namespace Gizmo.Go.UI.Helpers;

/// <summary>
/// Display rules of a reservation. Values that depend on "now" or on the device are computed here, not in Core.
/// </summary>
public static class ReservationDisplayHelper
{
    /// <summary>Gets the reservation start in the club time.</summary>
    public static DateTime GetStart(Reservation reservation) => reservation.BranchDate;

    /// <summary>Gets the reservation end in the club time.</summary>
    public static DateTime GetEnd(Reservation reservation) => reservation.BranchDate.AddMinutes(reservation.Duration);

    /// <summary>Gets the UTC offset of the club at the reservation start.</summary>
    public static TimeSpan GetClubOffset(Reservation reservation) => reservation.BranchDate - reservation.Date;

    /// <summary>Gets whether the device offset at the reservation start differs from the club offset.</summary>
    public static bool IsClubTimeHintNeeded(Reservation reservation)
    {
        var start = new DateTimeOffset(DateTime.SpecifyKind(reservation.Date, DateTimeKind.Utc));
        return TimeZoneInfo.Local.GetUtcOffset(start) != GetClubOffset(reservation);
    }

    /// <summary>Gets "Today" / "Tomorrow" in the club time; null for any other day.</summary>
    public static string? GetDayLabel(Reservation reservation, ILocalizationService localizationService)
    {
        var clubToday = (DateTime.UtcNow + GetClubOffset(reservation)).Date;

        return (GetStart(reservation).Date - clubToday).Days switch
        {
            0 => localizationService.GetString(nameof(Autogenerated.Resources.GO_HOME_TODAY)),
            1 => localizationService.GetString(nameof(Autogenerated.Resources.GO_HOME_TOMORROW)),
            _ => null
        };
    }

    /// <summary>Gets the date as "{label}, {d MMM}", or "{d MMM}" when the day has no label.</summary>
    public static string GetDateText(Reservation reservation, ILocalizationService localizationService)
    {
        var date = GetStart(reservation).ToString("d MMM", CultureInfo.CurrentCulture);
        var label = GetDayLabel(reservation, localizationService);

        return label is null ? date : $"{label}, {date}";
    }

    /// <summary>Gets the day label, or the date when the day has no label (compact form of the Home card).</summary>
    public static string GetDayText(Reservation reservation, ILocalizationService localizationService) =>
        GetDayLabel(reservation, localizationService) ?? GetStart(reservation).ToString("d MMM", CultureInfo.CurrentCulture);

    /// <summary>Gets the time range "HH:mm – HH:mm".</summary>
    public static string GetTimeText(Reservation reservation) => $"{GetStart(reservation):HH:mm} – {GetEnd(reservation):HH:mm}";

    /// <summary>Gets the session length: "2 h", "45 min" or "1 h 30 min".</summary>
    public static string GetDurationText(Reservation reservation, ILocalizationService localizationService)
    {
        var hours = reservation.Duration / 60;
        var minutes = reservation.Duration % 60;

        // the arguments go to GetString: GetString(key) formats the resource with no arguments and fails on "{0}"
        if (hours == 0)
            return localizationService.GetString(nameof(Autogenerated.Resources.GO_RESERVATIONS_DURATION_MINUTES), minutes);

        if (minutes == 0)
            return localizationService.GetString(nameof(Autogenerated.Resources.GO_RESERVATIONS_DURATION_HOURS), hours);

        return localizationService.GetString(nameof(Autogenerated.Resources.GO_RESERVATIONS_DURATION_HOURS_MINUTES), hours, minutes);
    }

    /// <summary>Gets an amount in the current culture (the server currency is applied to the culture).</summary>
    public static string FormatAmount(decimal amount) => amount.ToString("C", CultureInfo.CurrentCulture);

    /// <summary>Gets the cost text; a reservation without a cost shows a dash.</summary>
    public static string GetCostText(Reservation reservation) => reservation.Total == 0 ? "—" : FormatAmount(reservation.Total);

    /// <summary>Gets the resource key of the status label.</summary>
    public static string GetStatusKey(Reservation reservation) => reservation.Status switch
    {
        GoReservationStatus.Waiting => nameof(Autogenerated.Resources.GO_RESERVATIONS_STATUS_UPCOMING),
        GoReservationStatus.Active => nameof(Autogenerated.Resources.GO_HOME_RESERVATION_ACTIVE),
        GoReservationStatus.Canceled => nameof(Autogenerated.Resources.GO_RESERVATIONS_STATUS_CANCELED),
        GoReservationStatus.Expired => nameof(Autogenerated.Resources.GO_RESERVATIONS_STATUS_EXPIRED),
        _ => nameof(Autogenerated.Resources.GO_RESERVATIONS_STATUS_COMPLETED)
    };

    /// <summary>
    /// Gets the resource key of the Home status pill: "Active" during the session, otherwise the confirmation by the payment
    /// (an unpaid reservation is not confirmed).
    /// </summary>
    public static string GetHomeStatusKey(Reservation reservation)
    {
        if (reservation.Status == GoReservationStatus.Active)
            return nameof(Autogenerated.Resources.GO_HOME_RESERVATION_ACTIVE);

        return reservation.PaymentStatus switch
        {
            GoReservationPaymentStatus.PartiallySatisfied => nameof(Autogenerated.Resources.GO_HOME_RESERVATION_PARTIALLY_CONFIRMED),
            GoReservationPaymentStatus.NotSatisfied => nameof(Autogenerated.Resources.GO_HOME_RESERVATION_NOT_CONFIRMED),
            _ => nameof(Autogenerated.Resources.GO_HOME_RESERVATION_CONFIRMED)
        };
    }

    /// <summary>Gets whether the owner can cancel the reservation (the server still decides).</summary>
    public static bool CanCancel(Reservation reservation) => reservation.IsOwner && reservation.Status == GoReservationStatus.Waiting;

    /// <summary>Gets whether the PIN is shown: a not finished reservation that is paid or needs no payment.</summary>
    public static bool ShowPin(Reservation reservation) =>
        reservation.Status is GoReservationStatus.Waiting or GoReservationStatus.Active
        && reservation.PaymentStatus is GoReservationPaymentStatus.Satisfied or GoReservationPaymentStatus.NotRequired
        && !string.IsNullOrEmpty(reservation.Pin);

    /// <summary>Gets the paid part of the reservation cost.</summary>
    public static decimal GetPaidAmount(Reservation reservation) => reservation.Total - reservation.Outstanding;

    /// <summary>
    /// Gets the refund line of the cancel confirmation: <see cref="ReservationRefundState.None"/> when nothing is paid,
    /// <see cref="ReservationRefundState.Available"/> before the refund cutoff, <see cref="ReservationRefundState.Expired"/> after it.
    /// </summary>
    public static ReservationRefundState GetRefundState(Reservation reservation)
    {
        if (GetPaidAmount(reservation) <= 0)
            return ReservationRefundState.None;

        var cutoff = DateTime.SpecifyKind(reservation.Date, DateTimeKind.Utc).AddMinutes(-(reservation.CancellationGracePeriod ?? 0));

        return DateTime.UtcNow < cutoff ? ReservationRefundState.Available : ReservationRefundState.Expired;
    }

    /// <summary>
    /// Gets the name of the host of the reservation that is waiting or active; null when there is no such host or there are several.
    /// </summary>
    public static string? GetSingleHostName(Reservation reservation)
    {
        var hosts = reservation.Hosts
            .Where(host => host.Status is GoReservationHostStatus.Waiting or GoReservationHostStatus.Active)
            .ToList();

        return hosts.Count == 1 ? hosts[0].HostName : null;
    }
}

/// <summary>
/// Refund line of the reservation cancel confirmation.
/// </summary>
public enum ReservationRefundState
{
    /// <summary>Nothing is paid, no refund line.</summary>
    None,

    /// <summary>Canceled before the refund cutoff.</summary>
    Available,

    /// <summary>The refund time has expired.</summary>
    Expired
}
