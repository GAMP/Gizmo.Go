namespace Gizmo.Go.UI.Helpers;

/// <summary>
/// App-side documents of the "About the app" screen (stored in the app, placeholder texts for now).
/// </summary>
public static class AboutDocuments
{
    /// <summary>One document of the "Info" section.</summary>
    /// <param name="Id">Document id used by the route.</param>
    /// <param name="TitleKey">Resource key of the title.</param>
    /// <param name="TextKey">Resource key of the text (plain text).</param>
    public sealed record AboutDocument(int Id, string TitleKey, string TextKey);

    public static IReadOnlyList<AboutDocument> All { get; } =
    [
        new(1, nameof(Autogenerated.Resources.GO_PROFILE_ABOUT_DOC1_TITLE), nameof(Autogenerated.Resources.GO_PROFILE_ABOUT_DOC1_TEXT)),
        new(2, nameof(Autogenerated.Resources.GO_PROFILE_ABOUT_DOC2_TITLE), nameof(Autogenerated.Resources.GO_PROFILE_ABOUT_DOC2_TEXT)),
    ];

    public static AboutDocument? Find(int id) => All.FirstOrDefault(x => x.Id == id);
}
