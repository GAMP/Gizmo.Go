using System.Globalization;
using Gizmo.Go.Core.Models.Branch;
using Gizmo.UI.Services;

namespace Gizmo.Go.UI.Helpers
{
    /// <summary>
    /// Dates, start time slots and texts of the booking flow. Dates and times are club wall-clock values; the
    /// conversions use <see cref="BranchScheduleHelper"/>.
    /// </summary>
    internal static class BookingTimeHelper
    {
        /// <summary>
        /// Number of days of the date strip, starting from today of the club.
        /// </summary>
        internal const int DaysAhead = 14;

        /// <summary>
        /// Gets the start time slots of a day: every 30 minutes, 00:00 - 23:30.
        /// </summary>
        internal static readonly IReadOnlyList<TimeOnly> Slots =
            Enumerable.Range(0, 48).Select(index => new TimeOnly(index / 2, index % 2 * 30)).ToList();

        /// <summary>
        /// Gets today in the club time.
        /// </summary>
        internal static DateOnly GetClubToday(Branch branch) =>
            DateOnly.FromDateTime(BranchScheduleHelper.ToBranchTime(branch, DateTime.UtcNow));

        /// <summary>
        /// Gets whether the slot can be chosen: it is in the future of the club and exists exactly once
        /// (a daylight saving change makes a local time missing or ambiguous).
        /// </summary>
        internal static bool IsSlotSelectable(Branch branch, DateOnly date, TimeOnly time) =>
            IsSlotSelectable(BranchScheduleHelper.GetTimeZone(branch), BranchScheduleHelper.ToBranchTime(branch, DateTime.UtcNow), date, time);

        /// <summary>
        /// Gets whether the slot can be chosen, for many slots at once: the club zone and the club "now" are resolved
        /// by the caller once.
        /// </summary>
        internal static bool IsSlotSelectable(TimeZoneInfo zone, DateTime clubNow, DateOnly date, TimeOnly time)
        {
            var local = date.ToDateTime(time);

            return local > clubNow && BranchScheduleHelper.TryToUtc(zone, local, out _);
        }

        /// <summary>
        /// Gets whether the day has a selectable slot.
        /// </summary>
        internal static bool HasSelectableSlot(TimeZoneInfo zone, DateTime clubNow, DateOnly date) =>
            Slots.Any(slot => IsSlotSelectable(zone, clubNow, date, slot));

        /// <summary>
        /// Gets the first day of the strip that has a selectable slot; null when there is none.
        /// </summary>
        internal static DateOnly? GetFirstSelectableDay(Branch branch)
        {
            var zone = BranchScheduleHelper.GetTimeZone(branch);
            var now = BranchScheduleHelper.ToBranchTime(branch, DateTime.UtcNow);
            var today = DateOnly.FromDateTime(now);

            for (var offset = 0; offset < DaysAhead; offset++)
            {
                var day = today.AddDays(offset);
                if (HasSelectableSlot(zone, now, day))
                    return day;
            }

            return null;
        }

        /// <summary>
        /// Gets the session start in UTC; false when the local time does not exist or is ambiguous.
        /// </summary>
        internal static bool TryGetStartUtc(Branch branch, DateOnly date, TimeOnly time, out DateTime startUtc) =>
            BranchScheduleHelper.TryToUtc(branch, date.ToDateTime(time), out startUtc);

        /// <summary>Gets the date as "d MMM" in the current culture.</summary>
        internal static string FormatDate(DateOnly date) => date.ToString("d MMM", CultureInfo.CurrentCulture);

        /// <summary>Gets the date as "d MMM yyyy" in the current culture.</summary>
        internal static string FormatDayMonth(DateOnly date) => date.ToString("d MMMM", CultureInfo.CurrentCulture);

        internal static string FormatFullDate(DateOnly date) => date.ToString("d MMM yyyy", CultureInfo.CurrentCulture);

        /// <summary>Gets the time as "HH:mm".</summary>
        internal static string FormatTime(TimeOnly time) => time.ToString("HH:mm", CultureInfo.InvariantCulture);

        /// <summary>Gets the session time range "HH:mm – HH:mm" (the end may be on the next day).</summary>
        internal static string FormatTimeRange(TimeOnly start, int minutes) =>
            $"{FormatTime(start)} – {FormatTime(start.AddMinutes(minutes))}";

        /// <summary>Gets the session length: "2 h", "45 min" or "1 h 30 min".</summary>
        internal static string FormatDuration(int minutes, ILocalizationService localizationService)
        {
            var hours = minutes / 60;
            var rest = minutes % 60;

            // the arguments go to GetString: GetString(key) formats the resource with no arguments and fails on "{0}"
            if (hours == 0)
                return localizationService.GetString(nameof(Autogenerated.Resources.GO_RESERVATIONS_DURATION_MINUTES), rest);

            if (rest == 0)
                return localizationService.GetString(nameof(Autogenerated.Resources.GO_RESERVATIONS_DURATION_HOURS), hours);

            return localizationService.GetString(nameof(Autogenerated.Resources.GO_RESERVATIONS_DURATION_HOURS_MINUTES), hours, rest);
        }

        /// <summary>Gets the short weekday of a date in the current culture.</summary>
        internal static string FormatWeekday(DateOnly date) =>
            CultureInfo.CurrentCulture.DateTimeFormat.GetAbbreviatedDayName(date.DayOfWeek);

        /// <summary>Gets the short month of a date in the current culture.</summary>
        internal static string FormatMonth(DateOnly date) =>
            CultureInfo.CurrentCulture.DateTimeFormat.GetAbbreviatedMonthName(date.Month);

        /// <summary>Gets the host label "PC 09".</summary>
        internal static string FormatHost(int number, ILocalizationService localizationService) =>
            localizationService.GetString(nameof(Autogenerated.Resources.GO_BOOKING_PC_NUMBER), number.ToString("00", CultureInfo.InvariantCulture));

        /// <summary>Gets the hourly rate "3.50/h"; empty when the host group has no rate.</summary>
        internal static string FormatRate(decimal? rate, ILocalizationService localizationService) =>
            rate is { } value
                ? localizationService.GetString(nameof(Autogenerated.Resources.GO_BOOKING_RATE_PER_HOUR), ReservationDisplayHelper.FormatAmount(value))
                : string.Empty;
    }
}
